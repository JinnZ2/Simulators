#!/usr/bin/env python3
"""Builder L0 vs REVIEW-2 L2, per register concept. Reads the filed review text and the register
at a named commit; writes REVIEW2_COMPARISON_2026-11-20.md. Stdlib only.

    python3 studies/review/make_comparison.py            write
    python3 studies/review/make_comparison.py --check    compare, write nothing
"""
import json, os, re, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
REVIEW = os.path.join(HERE, "REVIEW2_in_map_GPT6_2026-11-20.md")
OUT = os.path.join(HERE, "REVIEW2_COMPARISON_2026-11-20.md")
L0_COMMIT = "2fd67dd"      # register the review copies were cut from
REVIEW_COMMIT = "7366f50"  # commit the reviewer read
# cause per concept number where L2 is not YES; a reading by the filer, from the reviewer's Reason text
HOME = {5, 8}


def git(*a):
    return subprocess.run(("git", "-C", ROOT) + a, capture_output=True, text=True, check=True).stdout


def l2():
    out = {}
    for n, name, v in re.findall(r"^(\d\d)\. (.+)\nin_map: (\w+)$", open(REVIEW, encoding="utf-8").read(), re.M):
        out[int(n)] = (name, v)
    return out


def build():
    reg0 = json.loads(git("show", L0_COMMIT + ":MULTI_HOME_REGISTER.json"))["rows"]
    now = json.load(open(os.path.join(ROOT, "MULTI_HOME_REGISTER.json"), encoding="utf-8"))["rows"]
    rev = l2()
    assert len(reg0) == len(rev) == len(now) == 28
    o = ["# Builder L0 vs REVIEW-2 L2, per concept", "",
         "Generated by `studies/review/make_comparison.py`. L0 = `in_map` in `MULTI_HOME_REGISTER.json` at `%s`" % L0_COMMIT,
         "(the builder's own reading). L2 = `REVIEW2_in_map_GPT6_2026-11-20.md` (GPT-6, read at `%s`)." % REVIEW_COMMIT,
         "strict now = `in_map` in the register in this tree, after the covers lists and the two added homes.", "",
         "cause: AGREE = both YES. GRAIN = the map holds the concept under an umbrella row with another name",
         "(all registered homes listed). HOME = a registered home was missing from every single map row.",
         "The cause column is the filer's reading of the reviewer's Reason line.", "",
         "| # | concept | L0 | L2 | same | cause | strict now |", "|---|---|---|---|---|---|---|"]
    c = {"L0": {}, "L2": {}, "cause": {}, "same": 0, "now": {}}
    for i, r in enumerate(reg0, 1):
        name, v2 = rev[i]
        assert name == r["concept"] == now[i - 1]["concept"], (i, name)
        v0 = r["in_map"]
        cause = "AGREE" if v2 == "YES" and v0 == "YES" else ("HOME" if i in HOME else "GRAIN")
        c["L0"][v0] = c["L0"].get(v0, 0) + 1
        c["L2"][v2] = c["L2"].get(v2, 0) + 1
        c["cause"][cause] = c["cause"].get(cause, 0) + 1
        c["same"] += v0 == v2
        vn = now[i - 1]["in_map"]
        c["now"][vn] = c["now"].get(vn, 0) + 1
        o.append("| %02d | %s | %s | %s | %s | %s | %s |" % (i, name, v0, v2, "yes" if v0 == v2 else "no", cause, vn))
    f = lambda d: ", ".join("%s %d" % kv for kv in sorted(d.items()))
    o += ["", "Counts (computed from the rows above):", "",
          "- L0: %s" % f(c["L0"]), "- L2: %s" % f(c["L2"]),
          "- same reading at L0 and L2: %d of 28" % c["same"],
          "- cause: %s" % f(c["cause"]), "- strict now: %s" % f(c["now"]), "",
          "Blob ids at `%s` (the bytes the reviewer read; the reviewer did not verify the sha256 values):" % REVIEW_COMMIT, ""]
    for p in ("MULTI_HOME_REGISTER_for_review_2026-11-20_v2.json", "concept_map_for_review_2026-11-20.json"):
        o.append("- `studies/review/%s`: `%s`" % (p, git("rev-parse", "%s:studies/review/%s" % (REVIEW_COMMIT, p)).strip()))
    o += ["", "## Owner's summary, excerpt as relayed in chat 2026-11-20 (the owner's text, not the reviewer's)", "",
          "```",
          "REVIEW-2 (GPT-6, L2: different family; memory ON, prior exposure to the repos, not to these files)",
          "  YES 15 · PARTIAL 13 · NO 0      vs the builder's L0: YES 25 · PARTIAL 3",
          "",
          "WHY THEY DIFFER (DERIVED)",
          "  GRAIN (11 rows)   the register names fine concepts; the map holds one umbrella row with every home listed",
          "                    L0 gate ← 02, 03 · known-answer/null harness ← 04, 06, 07 · anchor/return ← 10, 11",
          "                    UNKNOWN expiry ← 09 · percolation ← 17 · branching ← 18",
          "                    → GPT read \"names the concept\" strictly; the builder read umbrella coverage as YES",
          "  HOME (2 rows)     real gaps, independent of naming",
          "                    05 planted defects   study-aperture planted_defects.py missing from the map",
          "                                         (the builder said PARTIAL too → agreement, counted once per level: L0 + L2)",
          "                    08 non-detection     its homes are split across two rows; neither row lists both (the builder said YES)",
          "```", "",
          "Difference between that summary and the filed review text: the per-concept lines of the review",
          "count as shown under Counts above; the rows the summary lists under GRAIN number 10.",
          "The summary's figures are kept as relayed.", "",
          "## Notes", "",
          "- 03 and 07: PARTIAL at L0 and at L2 (same reading, cause GRAIN).",
          "- 05: PARTIAL at L0 and at L2. L0 gave a naming reason; L2 found the missing study-aperture home.",
          "- 08: YES at L0, PARTIAL at L2. The study-aperture home `non_detection.py` was in no map row at `%s`." % REVIEW_COMMIT,
          "- 25, 26: YES at both levels; the reviewer's remarks (possible two concepts; one location is nearest) are",
          "  carried in the map row note (25) and the location role `nearest` (26).", "",
          "Observer slots: null.", ""]
    return "\n".join(o)


if __name__ == "__main__":
    t = build()
    if "--check" in sys.argv:
        same = os.path.exists(OUT) and open(OUT, encoding="utf-8").read() == t
        print("REVIEW2_COMPARISON_2026-11-20.md", "identical" if same else "DIFFERS")
        sys.exit(0 if same else 1)
    open(OUT, "w", encoding="utf-8").write(t)
    print("wrote", OUT)
