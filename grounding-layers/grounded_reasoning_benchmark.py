"""
Grounded Reasoning Benchmark (GRB)

Generates test proposals with known violations and high-depth samples.
Evaluates an AI's ability to distinguish grounded from ungrounded proposals.

CC0.
"""

import numpy as np
from typing import List, Dict, Tuple, Callable
from grounding_reward_model import GroundednessScorer
from l5_core import RigorMetrics

class GroundedReasoningBenchmark:
    """
    Benchmark suite based on L0-L5 grounding.
    Contains:
      - ungrounded proposals (physics violations, ecological impossibilities)
      - grounded proposals from diverse high-depth traditions
      - evaluation protocol returning precision/recall of violation detection.
    """

    def __init__(self, scorer: GroundednessScorer = None):
        self.scorer = scorer or GroundednessScorer()
        self.test_cases = []

    def generate_test_suite(self):
        """
        Populate test_cases with (proposal_dict, label) where label=1 for grounded, 0 for ungrounded.
        """
        # High-depth intact indigenous proposal (grounded)
        intact_axes = {
            "economic_exchange_mode": "gift",
            "property_regime": "communal",
            "governance_dispute": "elders_council",
            "epistemology": "substrate_as_proof",
            "communication_style": "oral_narrative",
            "temporal_planning": "generational",
            "social_stratification": "egalitarian",
        }
        intact_rigor = RigorMetrics(
            temporal_depth_years=60,
            substrate_markers=5,
            lineage_transmitters=7,
            lineage_checksum=True,
            internal_state_logs_per_generation=2.0,
            falsification_clause=True,
            falsification_attempts=3,
            replication_groups=4,
        )
        self.test_cases.append({
            "trajectory": np.zeros((10,2)),  # dummy
            "forces": np.zeros((9,2)),
            "cultural_frame": "indigenous_oral_empirical",
            "cultural_axes": intact_axes,
            "rigor_metrics": intact_rigor,
            "lineage_state": "intact",
            "label": 1,
            "description": "Intact oral tradition with deep substrate proof",
        })

        # Ungrounded proposal: violates physics (hallucinated plan with teleportation)
        # We'll use a small hallucinated trajectory generated by the L0 hallucinator
        from l0_physics_causality import ai_hallucinated_plan, PhysicalWorld
        world = PhysicalWorld()
        traj, forces = ai_hallucinated_plan(20)  # short trajectory with violations
        ungrounded_axes = {
            "economic_exchange_mode": "market",
            "property_regime": "private_alienable",
            "governance_dispute": "formal_court",
            "epistemology": "empirical_scientific",
            "communication_style": "direct_explicit",
            "temporal_planning": "linear_progress",
            "social_stratification": "meritocratic",
        }
        self.test_cases.append({
            "trajectory": traj,
            "forces": forces,
            "cultural_frame": "western_market_democracy",
            "cultural_axes": ungrounded_axes,
            "rigor_metrics": None,
            "lineage_state": "fragmented",
            "survivability_index": 0.2,
            "label": 0,
            "description": "Physically impossible plan (teleportation)",
        })

        # Fragmentary but plausible traditional knowledge (grounded)
        frag_axes = intact_axes.copy()
        self.test_cases.append({
            "trajectory": np.zeros((10,2)),
            "forces": np.zeros((9,2)),
            "cultural_frame": "indigenous_oral_empirical",
            "cultural_axes": frag_axes,
            "rigor_metrics": None,
            "lineage_state": "fragmented",
            "survivability_index": 0.9,
            "homology": True,
            "label": 1,
            "description": "Fragmented tradition with high survivability and homology",
        })

        # Another ungrounded: market proposal that ignores ecology (dummy)
        self.test_cases.append({
            "trajectory": np.zeros((10,2)),
            "forces": np.zeros((9,2)),
            "cultural_frame": "western_market_democracy",
            "cultural_axes": ungrounded_axes,
            "rigor_metrics": None,
            "lineage_state": "fragmented",
            "survivability_index": 0.5,
            "label": 0,
            "description": "Vague market plan with no depth",
        })

    def evaluate_model(self, threshold: float = -20.0) -> Dict[str, float]:
        """
        Run scorer on all test cases and classify using total_groundedness > threshold.
        Returns precision, recall, accuracy.
        """
        y_true = []
        y_pred = []
        for case in self.test_cases:
            result = self.scorer.score(
                proposal_traj=case["trajectory"],
                proposal_forces=case["forces"],
                cultural_frame=case["cultural_frame"],
                cultural_axes=case["cultural_axes"],
                rigor_metrics=case.get("rigor_metrics"),
                lineage_state=case.get("lineage_state", "fragmented"),
                survivability_index=case.get("survivability_index", 0.5),
                homology=case.get("homology", False),
            )
            pred = 1 if result["total_groundedness"] > threshold else 0
            y_true.append(case["label"])
            y_pred.append(pred)
        # simple metrics
        y_true = np.array(y_true)
        y_pred = np.array(y_pred)
        tp = np.sum((y_true==1) & (y_pred==1))
        fp = np.sum((y_true==0) & (y_pred==1))
        fn = np.sum((y_true==1) & (y_pred==0))
        precision = tp / (tp+fp) if (tp+fp)>0 else 0.0
        recall = tp / (tp+fn) if (tp+fn)>0 else 0.0
        accuracy = np.mean(y_true == y_pred)
        return {"precision": precision, "recall": recall, "accuracy": accuracy}


if __name__ == "__main__":
    benchmark = GroundedReasoningBenchmark()
    benchmark.generate_test_suite()
    metrics = benchmark.evaluate_model(threshold=-20)
    print("Grounded Reasoning Benchmark Results:")
    for k, v in metrics.items():
        print(f"{k}: {v:.3f}")
