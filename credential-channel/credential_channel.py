HOURLY = 150.0                                              # [CHOICE 4]


class Refused(ValueError):
    """Raised at intake. A refused record never reaches a readout."""


def absent(v):
    return v is None or v == "" or v == "UNDECLARED"


# ===================================================================== I-1

def i1_route_correlation(candidates):                       # [CHOICE 1]
    """candidates: {route_a_score, route_b_score, performance}. Two rank
    correlations against performance. The claim under test: route A is
    uncorrelated or inverse while route B is positive."""
    a = [c["route_a_score"] for c in candidates]
    b = [c["route_b_score"] for c in candidates]
    perf = [c["performance"] for c in candidates]
    ra = spearman(a, perf)
    rb = spearman(b, perf)
    if ra is None or rb is None:
        return {"rho_a": ra, "rho_b": rb,
                "verdict": "NOT_EVALUABLE (a side is constant or too few)"}
    if ra <= 0 < rb:
        v = "the gate is uncorrelated or inverse; demonstrate outperforms"
    elif ra > 0 and rb > 0:
        v = "both routes track performance; the gate is not the problem here"
    else:
        v = "mixed; the claim is not supported by this pool"
    return {"rho_a": ra, "rho_b": rb, "verdict": v}


def i1_objection_coding(responses):                         # [CHOICE 2]
    """responses to a methodology objection: {status, kind} with kind in
    {'engage', 'cite_prior_usage'}. Ratio of engagement by speaker status.
    Prior use is not construct validity; the coding reports which move was
    made, it does not adjudicate the objection."""
    by = {}
    for r in responses:
        if r["kind"] not in ("engage", "cite_prior_usage"):
            raise Refused("i1_objection_coding: kind must be engage or cite_prior_usage")
        d = by.setdefault(r["status"], {"engage": 0, "cite_prior_usage": 0})
        d[r["kind"]] += 1
    out = {}
    for status, d in by.items():
        n = d["engage"] + d["cite_prior_usage"]
        out[status] = {"engage_share": d["engage"] / n, "n": n}
    return out


# ===================================================================== I-2

def i2_routing_cost(events):                                # [CHOICE 3,4]
    """events: {authorised, actual, resolution_cheap (bool), downtime_hours,
    external_cost}. Cost attributable to ROUTING (not the fault): the
    external cost plus downtime cost of any event resolved by someone other
    than the authorised responder with a cheap resolution.

    The order's mechanism note: the block is overshadowing/ripple avoidance,
    NOT procedure. Procedure makes it legible; a procedure change is not
    modelled as the cause, so this measures the routing gap directly.
    """
    total, per = 0.0, []
    for e in events:
        if absent(e.get("authorised")) or absent(e.get("actual")):
            raise Refused("i2_routing_cost: authorised and actual required")
        routed = (e["actual"] != e["authorised"]) and e.get("resolution_cheap", False)
        cost = (e.get("external_cost", 0.0) + e.get("downtime_hours", 0.0) * HOURLY) if routed else 0.0
        total += cost
        per.append({"routed": routed, "cost": cost})
    return {"n": len(events), "routing_cost_total": total,
            "n_routed": sum(1 for p in per if p["routed"]),
            "per_event": per,
            "mean_per_routed": None if not any(p["routed"] for p in per)
            else total / sum(1 for p in per if p["routed"])}


def routing_cost(external, downtime_hours):
    """The per-event routing-attributable cost of a routed event:
    external + downtime_hours * HOURLY. Registered in
    tools/known_answer.py."""
    return external + downtime_hours * HOURLY


# ===================================================================== I-3

def i3_gap_vs_exposure(rows):                               # [CHOICE 5]
    """rows: {confidence, hit_rate, exposure_years}. Regress the
    confidence-accuracy gap (confidence - hit_rate) on exposure. The order's
    prediction: the gap widens DOWNWARD with exposure, so the coefficient is
    negative -- confidence falls below hit rate as exposure grows,
    independent of accuracy."""
    y = [r["confidence"] - r["hit_rate"] for r in rows]
    x = [[r["exposure_years"] for r in rows]]
    beta, r2 = ols(y, x)
    if beta is None:
        return {"exposure_coef": None, "verdict": "NOT_EVALUABLE (singular)"}
    coef = beta[1]
    return {"exposure_coef": coef, "r_squared": r2,
            "verdict": ("gap widens downward with exposure (coef < 0)" if coef < 0
                        else "gap widens upward with exposure (coef > 0)" if coef > 0
                        else "no exposure trend")}


# ===================================================================== I-4

def i4_inventory_vs_exposure(rows):                         # [CHOICE 5]
    """rows: {inventory_score, exposure_years}. If the introversion score
    tracks exposure, the inventory is partly measuring history, not
    disposition. Same structure as I-3."""
    y = [r["inventory_score"] for r in rows]
    x = [[r["exposure_years"] for r in rows]]
    beta, r2 = ols(y, x)
    if beta is None:
        return {"exposure_coef": None, "verdict": "NOT_EVALUABLE (singular)"}
    coef = beta[1]
    return {"exposure_coef": coef, "r_squared": r2,
            "verdict": ("the inventory is partly measuring history, not "
                        "disposition (score tracks exposure)" if abs(coef) > 1e-6
                        else "no exposure trend; the score is not exposure-loaded")}


# ===================================================================== I-5

def i5_attribution_error(events):                           # [CHOICE 6]
    """events: {resolver_level, credited_level}. Attribution error rate by
    the level CREDITED, and its direction. Ground truth is the resolver;
    the credited party is who the record names."""
    by = {}
    for e in events:
        rl, cl = e["resolver_level"], e["credited_level"]
        d = by.setdefault(cl, {"events": 0, "errors": 0})
        d["events"] += 1
        if rl != cl:
            d["errors"] += 1
    out = {}
    for level, d in by.items():
        out[level] = {"events": d["events"],
                      "error_rate": None if d["events"] == 0 else d["errors"] / d["events"]}
    # direction: does credit flow up? share of errors where credited > resolver
    up = sum(1 for e in events if e["credited_level"] > e["resolver_level"])
    err = sum(1 for e in events if e["credited_level"] != e["resolver_level"])
    return {"by_credited_level": out,
            "upward_share": None if err == 0 else up / err,
            "reads": "a downstream statistic on these reports measures "
                     "REPORTING POSITION, not competence"}


# =============================================== constructed worlds (declared)

def i1_candidates(seed=1, n=40):
    """route B (demonstrate) tracks performance; route A (written) does
    not -- the order's claim as a declared model, so I-1 is a known-answer
    run on the correlation."""
    rng = random.Random(seed)
    out = []
    for _ in range(n):
        perf = rng.gauss(0, 1)
        out.append({"performance": perf,
                    "route_b_score": perf + rng.gauss(0, 0.3),
                    # the order's stronger claim: the written gate is
                    # inversely correlated with the ability selected for
                    "route_a_score": -0.4 * perf + rng.gauss(0, 0.7)})
    return out


def i1_objections():
    return ([{"status": "senior", "kind": "cite_prior_usage"}] * 7 +
            [{"status": "senior", "kind": "engage"}] * 3 +
            [{"status": "junior", "kind": "engage"}] * 8 +
            [{"status": "junior", "kind": "cite_prior_usage"}] * 2)


def i2_events():
    """CONSTRUCTED: the forklift-fuse and the four-mechanics events plus
    routine ones; the two field cases are resolved off-authorisation and
    cheaply."""
    return [
        {"authorised": "certified mechanic", "actual": "operator",
         "resolution_cheap": True, "downtime_hours": 2.0, "external_cost": 0.0},
        {"authorised": "certified mechanic", "actual": "operator",
         "resolution_cheap": True, "downtime_hours": 6.0, "external_cost": 0.0},
        {"authorised": "certified mechanic", "actual": "certified mechanic",
         "resolution_cheap": False, "downtime_hours": 1.0, "external_cost": 250.0},
        {"authorised": "operator", "actual": "operator",
         "resolution_cheap": True, "downtime_hours": 0.5, "external_cost": 0.0},
    ]


def i3_rows(seed=2, n=60):
    """gap falls with exposure (downward), independent of hit rate -- the
    order's prediction as a declared model."""
    rng = random.Random(seed)
    out = []
    for _ in range(n):
        exp = rng.uniform(0, 25)
        hit = rng.uniform(0.4, 0.8)
        conf = hit + 0.2 - 0.02 * exp + rng.gauss(0, 0.03)
        out.append({"confidence": conf, "hit_rate": hit, "exposure_years": exp})
    return out


def i4_rows(seed=4, n=60):
    """inventory score tracks exposure -- the produced-quiet model."""
    rng = random.Random(seed)
    out = []
    for _ in range(n):
        exp = rng.uniform(0, 25)
        out.append({"inventory_score": 3.0 + 0.05 * exp + rng.gauss(0, 0.2),
                    "exposure_years": exp})
    return out


def i5_events(seed=6, n=50):
    """credit flows up: the resolver is often a lower level than the
    credited party."""
    rng = random.Random(seed)
    out = []
    for _ in range(n):
        resolver = rng.choice([1, 1, 1, 2, 2, 3])
        credited = resolver + (rng.choice([1, 2]) if rng.random() < 0.6 else 0)
        out.append({"resolver_level": resolver, "credited_level": credited})
    return out


