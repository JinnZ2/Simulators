# ------------------------------------------------------------------ render

def refuse_selftest(name):
    sys.stderr.write("%s carries no selftest; run python3 test_credential.py\n"
                     % name)
    return 2


def render():
    out = ["WO-10  CREDENTIAL CHANNEL, five instruments   (data "
           "CONSTRUCTED, PROPOSED; no plant read)", "-" * 72]
    r = i1_route_correlation(i1_candidates())
    out.append("I-1  format gate   [CHOICE 1]")
    out.append("    route A (written) rho %.3f  route B (demonstrate) rho "
               "%.3f -> %s" % (r["rho_a"], r["rho_b"], r["verdict"]))
    oc = i1_objection_coding(i1_objections())
    for status in sorted(oc):
        out.append("    objection: %-7s engage share %.3f (n %d)   [CHOICE 2]"
                   % (status, oc[status]["engage_share"], oc[status]["n"]))
    out.append("")
    i2 = i2_routing_cost(i2_events())
    out.append("I-2  routing-cost join   [CHOICE 3,4]")
    out.append("    %d events, %d routed off-authorisation; cost "
               "attributable to routing %.0f (mean per routed %.0f)"
               % (i2["n"], i2["n_routed"], i2["routing_cost_total"],
                  i2["mean_per_routed"]))
    out.append("")
    i3 = i3_gap_vs_exposure(i3_rows())
    out.append("I-3  confidence-accuracy gap vs exposure   [CHOICE 5]")
    out.append("    exposure coef %+.4f  r2 %.3f -> %s"
               % (i3["exposure_coef"], i3["r_squared"], i3["verdict"]))
    out.append("")
    i4 = i4_inventory_vs_exposure(i4_rows())
    out.append("I-4  inventory score vs exposure   [CHOICE 5]")
    out.append("    exposure coef %+.4f  r2 %.3f -> %s"
               % (i4["exposure_coef"], i4["r_squared"], i4["verdict"]))
    out.append("")
    i5 = i5_attribution_error(i5_events())
    out.append("I-5  attribution mismatch by credited level   [CHOICE 6]")
    for lvl in sorted(i5["by_credited_level"]):
        d = i5["by_credited_level"][lvl]
        out.append("    level %d  mismatch rate %s (n %d)"
                   % (lvl, "None" if d["error_rate"] is None else "%.3f" % d["error_rate"],
                      d["events"]))
    out.append("    upward share of mismatches %.3f -- %s"
               % (i5["upward_share"], i5["reads"]))
    out.append("")
    out.append("carried: Combine-Cognitive-Architecture (not in this tree, "
               "overlay not attributed); the specialisation assumption "
               "(NOT YET RUNNABLE, requires a measurand)")
    return "\n".join(out) + "\n"


def main(argv):
    if "--selftest" in argv:
        return refuse_selftest("credential_channel.py")
    if "--choices" in argv:
        for k in sorted(CHOICES):
            sys.stdout.write("[CHOICE %d] %s\n" % (k, CHOICES[k]))
        return 0
    sys.stdout.write(render())
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
