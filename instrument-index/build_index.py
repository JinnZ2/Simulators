def _axis_line(rows):
    verdict, rated, claim_only, frac = axis_check(rows)
    if frac is None:
        return "%s (rated rows: 0)" % verdict
    return "%s (claim-only %d / rated %d = %.3f, threshold %.2f)" % (
        verdict, claim_only, rated, frac, AXIS_THRESHOLD)


def write_tsv(path, rows, repos, flags, stamp):
    """Agent view."""
    out = []
    out.append("# %s" % GENERATED_NOTE)
    out.append("# stamp: %s" % stamp)
    for rec in repos:
        out.append("# repo: %s  state: %s  rows: %d  built_against: %s" % (
            rec["label"], rec["state"], len(rec["rows"]), rec["built_against"]))
    out.append("# rows: %d" % len(rows))
    out.append("# estimate: %s" % ESTIMATE_NOTE)
    out.append("# axis-check: %s" % _axis_line(rows))
    out.append("# unrated: %d (to-do, located, not hidden)"
               % len(unrated_rows(rows)))
    out.append("# total_load_tok_est: %d" % total_tok_est(rows))
    out.append("# flags: %d" % len(flags))
    out.append("\t".join(FIELDS))
    for row in rows:
        out.append("\t".join(scrub(row[f]) for f in FIELDS))
    with open(path, "w") as fh:
        fh.write("\n".join(out) + "\n")


def _repo_load(rec):
    return sum(int(r["load_tok_est"]) for r in rec["rows"])


def write_md(path, rows, repos, flags, stamp):
    """Human view."""
    out = []
    out.append("# INSTRUMENT-INDEX")
    out.append("")
    out.append(GENERATED_NOTE)
    out.append("")
    out.append("Stamp: %s" % stamp)
    out.append("")
    out.append("## Build state")
    out.append("")
    out.append("| repo | state | rows |")
    out.append("| --- | --- | --- |")
    for rec in repos:
        out.append("| %s | %s | %d |" % (rec["label"], rec["state"],
                                         len(rec["rows"])))
    out.append("")
    out.append("## Instruments")
    out.append("")
    # [REBUILD-CHOICE] repos sorted by load cost descending; NOT-SCANNED
    # repos sort last, since they have no load to rank.
    ordered = sorted(
        repos,
        key=lambda rec: (rec["state"] == NOT_SCANNED, -_repo_load(rec),
                         rec["label"]),
    )
    for rec in ordered:
        out.append("### %s" % rec["label"])
        out.append("")
        if rec["state"] == NOT_SCANNED:
            out.append("Unknown contents, not an empty repo.")
            out.append("")
            continue
        rated = [r for r in rec["rows"] if r["input_shape"] != UNRATED]
        if not rated:
            out.append("Scanned, no rated instruments found (%d file(s) "
                       "unrated)." % len(rec["rows"]))
            out.append("")
            continue
        out.append("| catches | id | name | path | input_shape | run_cost | "
                   "run_basis | status | gate | load_tok_est |")
        out.append("| --- | --- | --- | --- | --- | --- | --- | --- | --- "
                   "| --- |")
        for row in rated:
            out.append("| %s | %s | %s | %s | %s | %s | %s | %s | %s | %s |" % (
                row["catches"], row["id"], row["name"], row["path"],
                row["input_shape"], row["run_cost"],
                row["run_basis"] or "(empty)", row["status"], row["gate"],
                row["load_tok_est"]))
        out.append("")
    out.append("## Axis check")
    out.append("")
    out.append(_axis_line(rows))
    out.append("")
    out.append("The threshold is %.2f: a rated set more than %.0f%% of which "
               "carries CLAIM alone does not partition." % (
                   AXIS_THRESHOLD, AXIS_THRESHOLD * 100))
    out.append("")
    out.append("## Validity flags")
    out.append("")
    if not flags:
        out.append("None at this build.")
    else:
        out.append("| row | field | note |")
        out.append("| --- | --- | --- |")
        for rid, field, note in flags:
            out.append("| %s | %s | %s |" % (rid, field, note))
    out.append("")
    out.append("Flags never alter the row value.")
    out.append("")
    out.append("## Unrated set")
    out.append("")
    out.append("To-do, located, not hidden. %d row(s)."
               % len(unrated_rows(rows)))
    out.append("")
    for row in unrated_rows(rows):
        out.append("- %s" % row["id"])
    out.append("")
    out.append("## Load")
    out.append("")
    out.append("total_load_tok_est: %d" % total_tok_est(rows))
    out.append("")
    out.append(ESTIMATE_NOTE)
    out.append("")
    out.append("## Coverage declaration")
    out.append("")
    out.append("[REBUILD-CHOICE] The original six lines were not recovered. "
               "Replaceable when the original turns up.")
    out.append("")
    for line in COVERAGE_DECLARATION:
        out.append("- %s" % line)
    out.append("")
    out.append("built_against states: %s" % ", ".join(
        "%s=%s" % (rec["label"], rec["built_against"]) for rec in repos))
    out.append("")
    with open(path, "w") as fh:
        fh.write("\n".join(out) + "\n")


