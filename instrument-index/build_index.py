def axis_check(rows):
    """[RECOVERED] pre-stated falsifier, run on every build."""
    rated = [r for r in rows if r["input_shape"] != UNRATED]
    if not rated:
        return AXIS_UNRATED, 0, 0, None
    claim_only = [r for r in rated if shape_list(r["input_shape"]) == ["CLAIM"]]
    frac = float(len(claim_only)) / float(len(rated))
    verdict = AXIS_FALSIFIED if frac > AXIS_THRESHOLD else AXIS_HOLDS
    return verdict, len(rated), len(claim_only), frac


def claim_only_fraction(rows):
    """Fraction of rated rows whose ONLY shape is CLAIM. None when no rated
    rows: an empty rated set is not a fraction of zero."""
    return axis_check(rows)[3]


def unrated_rows(rows):
    return [r for r in rows if r["input_shape"] == UNRATED]


def total_tok_est(rows):
    return sum(int(r["load_tok_est"]) for r in rows)


