def blank_row():
    row = dict.fromkeys(FIELDS, UNRATED)
    row["run_basis"] = ""
    row["gate"] = GATE_DEFAULT
    return row


def collect(repo_args):
    """[RECOVERED] collect() once; neither rendering derives from the other."""
    rows = []
    repos = []
    flags = []
    for label in repo_args:
        if not os.path.isdir(label):
            # [RECOVERED] path passed but missing -> NOT-SCANNED, distinct
            # from scanned with zero rated rows.
            # [REBUILD-CHOICE] a path that exists and is not a directory is
            # NOT-SCANNED too.
            repos.append({"label": label, "state": NOT_SCANNED,
                          "built_against": NOT_SCANNED, "rows": []})
            continue
        rels = walk_repo(label)
        stamp = built_against(label, rels)
        overrides = read_overrides(label)
        repo_rows = []
        for rel in rels:
            full = os.path.join(label, rel)
            with open(full, "rb") as fh:
                raw = fh.read()
            text = raw.decode("utf-8", "replace")
            row = blank_row()
            # [REBUILD-CHOICE] id is '<repo label>:<relative path>'.
            row["id"] = "%s:%s" % (label, rel)
            # [REBUILD-CHOICE] repo is the path exactly as passed.
            row["repo"] = label
            row["path"] = rel
            row["load_bytes"] = str(len(raw))
            row["load_tok_est"] = str(len(raw) // 4)
            row["built_against"] = stamp
            over = overrides.get(rel, {})
            head = parse_header(text)
            # [RECOVERED] the in-file header wins over the override.
            for key in ("name", "input_shape", "catches", "status", "gate"):
                if key in head:
                    row[key] = head[key]
                elif key in over:
                    row[key] = over[key]
            if "run_cost" in head:
                cost, basis = split_run_cost(head["run_cost"])
                row["run_cost"] = cost
                row["run_basis"] = basis
            else:
                if "run_cost" in over:
                    row["run_cost"] = over["run_cost"]
                if "run_basis" in over:
                    row["run_basis"] = over["run_basis"]
            flags.extend(row_flags(row))
            repo_rows.append(row)
        rows.extend(repo_rows)
        repos.append({"label": label, "state": "SCANNED",
                      "built_against": stamp, "rows": repo_rows})
    return rows, repos, flags


