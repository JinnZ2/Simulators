USAGE = "usage: build_index.py --tsv OUT.tsv --md OUT.md repo1 repo2 ..."


def main(argv):
    if "--selftest" in argv:
        sys.stderr.write(
            "build_index.py has no --selftest. Run:\n"
            "  python3 instrument-index/tests/test_build_index.py\n")
        return 2
    tsv = md = None
    repos = []
    i = 0
    while i < len(argv):
        arg = argv[i]
        if arg == "--tsv" and i + 1 < len(argv):
            tsv = argv[i + 1]
            i += 2
        elif arg == "--md" and i + 1 < len(argv):
            md = argv[i + 1]
            i += 2
        else:
            repos.append(arg)
            i += 1
    if tsv is None or md is None or not repos:
        sys.stderr.write(USAGE + "\n")
        return 2
    stamp = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    rows, repo_states, flags = collect(repos)
    write_tsv(tsv, rows, repo_states, flags, stamp)
    write_md(md, rows, repo_states, flags, stamp)
    for rid, field, note in flags:
        sys.stderr.write("FLAG %s %s: %s\n" % (rid, field, note))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
