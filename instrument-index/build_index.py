def fingerprint(root, relpaths):
    """[REBUILD-CHOICE] sha256 over sorted 'relpath\\0mtime_ns' lines."""
    h = hashlib.sha256()
    for rel in sorted(relpaths):
        full = os.path.join(root, rel)
        try:
            mtime = os.stat(full).st_mtime_ns
        except OSError:
            mtime = 0
        h.update(rel.encode("utf-8"))
        h.update(b"\0")
        h.update(str(mtime).encode("ascii"))
        h.update(b"\n")
    return "nogit-" + h.hexdigest()[:10]


def built_against(root, relpaths):
    """[RECOVERED] short git hash, else nogit-<...>. Never guess."""
    try:
        out = subprocess.run(
            ["git", "-C", root, "rev-parse", "--short", "HEAD"],
            stdout=subprocess.PIPE, stderr=subprocess.DEVNULL,
        )
    except (OSError, ValueError):
        return fingerprint(root, relpaths)
    if out.returncode != 0:
        return fingerprint(root, relpaths)
    short = out.stdout.decode("ascii", "replace").strip()
    if not short:
        return fingerprint(root, relpaths)
    return short


