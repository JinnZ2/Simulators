def row_flags(row):
    """Flags never alter the row value."""
    out = []
    for token in shape_list(row["input_shape"]):
        if token not in INPUT_SHAPES:
            out.append((row["id"], "input_shape",
                        "value outside the enum: %s" % token))
    if row["run_cost"] not in RUN_COSTS:
        out.append((row["id"], "run_cost",
                    "value outside the enum: %s (kept, not normalized)"
                    % row["run_cost"]))
    if row["run_cost"] != UNRATED and not row["run_basis"]:
        out.append((row["id"], "run_basis",
                    "run_cost is %s and run_basis is empty" % row["run_cost"]))
    if row["run_basis"] and row["run_basis"] not in RUN_BASES:
        out.append((row["id"], "run_basis",
                    "value outside the enum: %s" % row["run_basis"]))
    return out


