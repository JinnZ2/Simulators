def scrub(value):
    """[RECOVERED] tabs/newlines in values -> spaces."""
    out = []
    for ch in str(value):
        out.append(" " if ch in "\t\r\n" else ch)
    return "".join(out).strip()


def parse_header(text):
    """[RECOVERED] in-file header, parsed from the leading comment block.

    Stops at the first non-comment line. [REBUILD-CHOICE] a blank line is
    not a comment line, so a blank line terminates the block.
    """
    found = {}
    for line in text.splitlines():
        stripped = line.strip()
        if not stripped.startswith("#"):
            break
        body = stripped.lstrip("#").strip()
        if ":" not in body:
            continue
        key, _, value = body.partition(":")
        key = key.strip()
        if key in HEADER_KEYS:
            found[HEADER_KEYS[key]] = scrub(value)
    return found


def split_run_cost(raw):
    """RUN-COST: TRIVIAL (author-estimate) -> ('TRIVIAL', 'author-estimate').

    The value in parentheses is run_basis. [REBUILD-CHOICE] the
    parenthetical is optional at parse time; a run_cost other than UNRATED
    with an empty run_basis is a flag, not a parse failure.
    """
    raw = scrub(raw)
    cost, basis = raw, ""
    if raw.endswith(")") and "(" in raw:
        head, _, tail = raw.rpartition("(")
        cost = head.strip()
        basis = tail[:-1].strip()
    return cost, basis


def shape_list(value):
    """input_shape is multi-valued, pipe-separated."""
    if value == UNRATED:
        return []
    return [p.strip() for p in value.split("|") if p.strip()]


