    if not os.path.isfile(path):
        return {}
    with open(path, "r") as fh:
        raw = json.load(fh)
    out = {}
    for key, rec in raw.items():
        if not isinstance(rec, dict):
            continue
        out[key.replace(os.sep, "/")] = {
            k: scrub(v) for k, v in rec.items() if k in FIELDS
        }
    return out


